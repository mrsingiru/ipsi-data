"""해가 안 적힌 날짜 읽기 점검(2026-10-25 — 작년 글의 날짜를 올해로 읽던 오류). 네트워크 없이 돈다: python scripts/test_dates.py"""
import datetime, sys, os
sys.path.insert(0, os.path.dirname(__file__))
import fetch_official as F
T = datetime.date(2026, 10, 25)
fails = []
def check(name, got, want):
    print(('ok  ' if got == want else 'FAIL') + ' ' + name, got if got != want else '')
    if got != want: fails.append(name)
def ds(text): return [d for l in F.date_lines(text, [], T, 'x') for d in l['dates']]
# ① 작년(2026학년도) 글: 해 없는 날짜는 2025년
jb = '과학영재교육원, 2026학년도 초·중등 심화과정 신입생 모집\n원서 접수는 오는 10월 27일부터 11월 5일까지 선발사이트에서 진행된다.\n전형은 11월 15일 1차, 11월 29일 심층면접.'
check('① 2026학년도 글 → 2025년', ds(jb), ['2025-10-27', '2025-11-05', '2025-11-15', '2025-11-29'])
# ② 올해(2027학년도) 글: 가을은 2026년, 1월은 2027년
k = '2027학년도 고등학교 입학전형\n원서 접수 12월 8일 ~ 12월 10일\n배정 발표 1월 12일'
check('② 2027학년도 글 → 2026·2027', ds(k), ['2026-12-08', '2026-12-10', '2027-01-12'])
# ③ 학년도 없는 글은 예전처럼(오늘에 가까운 해)
check('③ 학년도 없음 → 예전 규칙', ds('설명회 11월 14일 개최'), ['2026-11-14'])
# ④ 요일이 있으면 학년도 안에서 요일이 맞는 날
check('④ 2026학년도 + 요일(월)', ds('2026학년도 모집\n원서 10. 27.(월)'), ['2025-10-27'])
check('④ 2027학년도 + 요일(화)', ds('2027학년도 일정표\n합격자 발표 | 10. 27.(화)\n배정 발표 | ’27. 1. 12.(화)'), ['2026-10-27', '2027-01-12'])
# ⑤ 해가 적힌 날짜는 그대로, 범위 끝은 앞 날짜를 따름
check('⑤ 전체 날짜·범위', ds('2026학년도 요강\n접수 2026. 12. 28. ~ 1. 3.'), ['2026-12-28', '2027-01-03'])
# ⑥ 여러 학년도: 가장 많이 나온 것(같으면 큰 것)
check('⑥ 많이 나온 학년도', ds('2027학년도 선발 요강(2027학년도 영재교육대상자) — 2026학년도와 달라진 점\n원서 11월 2일'), ['2026-11-02'])
print('FAILS:', fails); sys.exit(1 if fails else 0)
